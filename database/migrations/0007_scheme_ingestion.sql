-- =============================================================================
-- 0007_scheme_ingestion.sql
-- YOGYA database migration 7: scheme ingestion metadata and required documents.
--
-- Purpose:
--   * Adds ingestion and display metadata columns to schemes and scheme_versions
--     (benefit_summary, deadline_text as stated by the source, ingestion_source_type,
--     created_by, updated_at). Each column is added only if missing.
--   * Adds scheme_required_documents: the document checklist for one scheme version.
--   * Enables and FORCES row-level security on scheme_required_documents, with a
--     public read policy (published parent version only) and an admin policy.
--
-- Depends on: 0001 through 0006 (0002 schemes/scheme_versions/scheme_sources,
--   0005 is_admin() and the anon/authenticated grant pattern).
-- Forward-only and additive. Do NOT edit this file after it has been applied;
--   fix problems in a new migration. Safe to re-run: ADD COLUMN IF NOT EXISTS,
--   CREATE TABLE IF NOT EXISTS, and DROP POLICY IF EXISTS before CREATE POLICY.
-- No audit triggers here: audit_logs rows are written by application code.
-- Run inside a transaction.
--
-- DATA RULE: deadline_text is the deadline as worded by the official source. It is
-- never computed or invented. Benefits and requirements come only from verified rules.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Additive columns on schemes and scheme_versions.
-- updated_at already exists on both tables (0002), so its ADD COLUMN is a no-op
-- and is kept only to match the specification.
-- -----------------------------------------------------------------------------
ALTER TABLE schemes
  ADD COLUMN IF NOT EXISTS benefit_summary       text,
  ADD COLUMN IF NOT EXISTS deadline_text         text,
  ADD COLUMN IF NOT EXISTS ingestion_source_type text
    CHECK (ingestion_source_type IN ('manual', 'url_import')),
  ADD COLUMN IF NOT EXISTS created_by            uuid REFERENCES users(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS updated_at            timestamptz DEFAULT now();

ALTER TABLE scheme_versions
  ADD COLUMN IF NOT EXISTS benefit_summary       text,
  ADD COLUMN IF NOT EXISTS deadline_text         text,
  ADD COLUMN IF NOT EXISTS ingestion_source_type text
    CHECK (ingestion_source_type IN ('manual', 'url_import')),
  ADD COLUMN IF NOT EXISTS created_by            uuid REFERENCES users(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS updated_at            timestamptz DEFAULT now();

-- -----------------------------------------------------------------------------
-- 2. scheme_required_documents
-- Document checklist for one scheme version. Cascades with its parent version.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS scheme_required_documents (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  scheme_version_id   uuid NOT NULL REFERENCES scheme_versions(id) ON DELETE CASCADE,
  document_name       text NOT NULL CHECK (length(trim(document_name)) > 0),
  -- TBD: list of document kinds (not specified in the PRD).
  document_kind       text NOT NULL DEFAULT 'other',
  is_mandatory        boolean NOT NULL DEFAULT true,
  source_id           uuid REFERENCES scheme_sources(id),
  created_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT scheme_required_documents_version_name_key
    UNIQUE (scheme_version_id, document_name)
);

-- The unique constraint above already indexes scheme_version_id as its leading
-- column, so no separate index on scheme_version_id is created.

-- -----------------------------------------------------------------------------
-- 3. Row-level security on scheme_required_documents.
-- -----------------------------------------------------------------------------
ALTER TABLE scheme_required_documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE scheme_required_documents FORCE ROW LEVEL SECURITY;

-- Guests and students: read only when the parent scheme version is published.
DROP POLICY IF EXISTS scheme_required_documents_public_read ON scheme_required_documents;
CREATE POLICY scheme_required_documents_public_read ON scheme_required_documents
  FOR SELECT TO anon, authenticated
  USING (EXISTS (
    SELECT 1 FROM scheme_versions v
    WHERE v.id = scheme_required_documents.scheme_version_id
      AND v.status = 'published'));

-- Admin: full access. Same pattern as the other catalogue tables in 0005.
DROP POLICY IF EXISTS scheme_required_documents_admin_all ON scheme_required_documents;
CREATE POLICY scheme_required_documents_admin_all ON scheme_required_documents
  FOR ALL TO authenticated
  USING (is_admin())
  WITH CHECK (is_admin());

-- -----------------------------------------------------------------------------
-- 4. Grants. Start from zero for anon and authenticated, then add back the verbs
-- the policies above allow. Anon reads published rows only (policy above).
-- Authenticated gets write verbs too, because the admin policy needs them; the
-- policy restricts every non-admin to zero rows.
-- -----------------------------------------------------------------------------
REVOKE ALL ON scheme_required_documents FROM anon, authenticated;

GRANT SELECT ON scheme_required_documents TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON scheme_required_documents TO authenticated;
